"""Synthetic feature-vector generation from the trained VAE decoder.

Procedure: z ~ N(0, temperature^2 I) -> decoder mean x_hat(z) (standardised model space)
           -> FeatureTransformer.inverse_transform -> V1-V28 + Amount (original scale).

Generated rows are vectors in the anonymised PCA feature space of the source data. They are not
real or interpretable transaction records, and they carry no fraud label.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
import torch

from src.data.preprocess import FeatureTransformer
from src.models.vae import VAE
from src.utils.io import save_json, sha256_file

DISCLAIMER = (
    "Synthetic samples are vectors in the anonymised PCA feature space (V1-V28) plus Amount, generated by a VAE "
    "trained on normal transactions. They are not real or interpretable transaction records: the original features "
    "and PCA loadings were never published, so rows cannot be mapped to merchants, cards, places or customers. "
    "No fraud label is attached. Source data: Credit Card Fraud Detection, ULB MLG / Worldline (Kaggle "
    "mlg-ulb/creditcardfraud), ODbL 1.0 / DbCL 1.0; Dal Pozzolo et al., CIDM 2015."
)


@torch.no_grad()
def fit_decoder_noise_std(model: VAE, X_train: np.ndarray, seed: int, batch_size: int = 8192) -> np.ndarray:
    """Per-feature std of the decoder's Gaussian noise, estimated from training residuals x - x_hat(z), z ~ q(z|x).

    This is the maximum-likelihood variance of a diagonal Gaussian decoder given the trained network
    (training rows only, no labels). It is used by the 'decoder mean + noise' sampling variant.
    """
    model.eval()
    generator = torch.Generator().manual_seed(seed)
    sq_sum = torch.zeros(model.cfg.input_dim, dtype=torch.float64)
    device = next(model.parameters()).device
    for start in range(0, len(X_train), batch_size):
        x = torch.from_numpy(np.ascontiguousarray(X_train[start:start + batch_size], dtype=np.float32)).to(device)
        recon = model(x, sample=True, generator=generator).recon
        sq_sum += (x - recon).pow(2).sum(dim=0).double().cpu()
    return np.sqrt((sq_sum / len(X_train)).numpy())


@torch.no_grad()
def generate_model_space(model: VAE, n: int, seed: int, temperature: float = 1.0, noise_std: np.ndarray | None = None,
                         batch_size: int = 8192) -> np.ndarray:
    """n samples in standardised model space (float64).

    noise_std=None -> decoder mean x_hat(z) (primary sampler).
    noise_std=array -> x_hat(z) + eps, eps ~ N(0, diag(noise_std^2)) (full sample from p(x|z)).
    """
    model.eval()
    generator = torch.Generator().manual_seed(seed)
    chunks = []
    for start in range(0, n, batch_size):
        m = min(batch_size, n - start)
        chunks.append(model.sample_prior(m, temperature=temperature, generator=generator).double().cpu().numpy())
    Z = np.concatenate(chunks)
    if noise_std is not None:
        Z = Z + np.random.default_rng(seed + 1).normal(size=Z.shape) * np.asarray(noise_std)[None, :]
    if not np.isfinite(Z).all():
        raise FloatingPointError("Generated samples contain NaN/Inf")
    return Z


def generate_synthetic(model: VAE, transformer: FeatureTransformer, n: int, seed: int, temperature: float = 1.0,
                       noise_std: np.ndarray | None = None) -> tuple[np.ndarray, pd.DataFrame]:
    Z = generate_model_space(model, n, seed, temperature, noise_std)
    return Z, transformer.inverse_transform(Z)


def export_synthetic(df: pd.DataFrame, out_dir: Path, name: str, meta: dict) -> Path:
    """Write CSV + metadata JSON + README to data/synthetic (separate from the original dataset)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / f"{name}.csv"
    df.to_csv(csv_path, index=False, float_format="%.6f")
    save_json({**meta, "file": csv_path.name, "rows": len(df), "columns": list(df.columns),
               "csv_sha256": sha256_file(csv_path), "created_utc": datetime.now(timezone.utc).isoformat(),
               "has_class_column": False, "disclaimer": DISCLAIMER}, out_dir / f"{name}.meta.json")
    (out_dir / "README.md").write_text(
        "# Synthetic data\n\n"
        f"{DISCLAIMER}\n\n"
        "Each CSV has columns `V1`–`V28` and `Amount`. It has no `Class` and no `Time` column. "
        "The matching `.meta.json` records the model checkpoint, seed, sampling temperature and file hash.\n",
        encoding="utf-8")
    return csv_path
